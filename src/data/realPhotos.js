// Real Meerav packshot photography (supplied by the brand), mapped to the
// actual product ids they depict in the live Supabase `products` table.
// Used to override the DB's placeholder/stock image for these specific SKUs
// wherever we want the authentic brand pack to show instead.
export const productPhotoOverrides = {
  p1: "/images/products/meerav_3.jpg", // Meerav Authentic Aloo Bhujia -> Bhujia pack
  p2: "/images/products/meerav_1.jpg", // Meerav Royal Bikaneri Papad & Moth Bhujia -> Papad pack
  p12: "/images/products/meerav_5.jpg", // Meerav Salted Crispy Moong Dal -> Moong Dal pack
  p19: "/images/products/meerav_4.jpg", // Meerav Golden Cornflakes Potato Chips & Mixture -> Chips pack
  p22: "/images/products/meerav_7.jpg", // Meerav All-In-One Imperial Namkeen -> Namkeen pack
  p24: "/images/products/meerav_6.jpg", // Meerav Masala Raita Boondi Pearls -> Raita Boondi pack
  p4: "/images/products/meerav_2.jpg", // Meerav Shahi Kaju Dry Fruit Mixture -> Mixture pack
  p56: "/images/products/meerav_8.jpg", // Meerav Masala Roasted Peanuts -> Masala Peanuts pack
};

export function withRealPhoto(product) {
  const override = productPhotoOverrides[product.id];
  return override ? { ...product, image: override } : product;
}

